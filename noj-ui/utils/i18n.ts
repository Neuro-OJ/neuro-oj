export function normalizeLocale(value: unknown): Locale {
  return value === 'en-US' || value === 'en' ? 'en-US' : DEFAULT_LOCALE;
}

export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const template = messages[locale][key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params?.[name] ?? `{${name}}`));
}

/** 机器错误码到本地化文案的集中映射；未知 code 才回退到后端的具体原因。 */
export function translateErrorCode(code: string | undefined, locale: Locale): string | undefined {
  if (!code) return undefined;
  const message = messages[locale][`error.${code}`];
  return message;
}
